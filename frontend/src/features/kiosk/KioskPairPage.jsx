import { useState } from "react";
import { Link, useNavigate } from "react-router";
import { kioskApi } from "../../api/client.js";
import "./kiosk.css";

export default function KioskPairPage() {
  const [code, setCode] = useState("");
  const [error, setError] = useState("");
  const [pending, setPending] = useState(false);
  const navigate = useNavigate();

  async function pair(event) {
    event.preventDefault();
    setPending(true);
    setError("");
    try {
      await kioskApi.activate(code.trim().toUpperCase());
      navigate("/kiosk", { replace: true });
    } catch (cause) {
      setError(cause.message);
    } finally {
      setPending(false);
    }
  }

  return (
    <main className="kiosk-shell kiosk-pair-shell">
      <header className="kiosk-header">
        <div className="kiosk-brand-group">
          <a className="kiosk-wordmark" href="/kiosk" aria-label="Clinic queue kiosk">
            <span className="kiosk-wordmark-badge" aria-hidden="true">Q</span>
            <div className="kiosk-brand-text">
              <span className="kiosk-brand-title">CLINIC QUEUE</span>
              <span className="kiosk-brand-subtitle">DEVICE ENROLLMENT</span>
            </div>
          </a>
        </div>
        <div className="kiosk-header-status">
          <span className="kiosk-status-pill kiosk-status-pill-setup">
            <span className="kiosk-status-dot kiosk-status-dot-amber" />
            <span>STAFF CONFIGURATION</span>
          </span>
        </div>
      </header>

      <section className="kiosk-main kiosk-pair-main" aria-labelledby="pair-heading">
        <div className="kiosk-stage-hero">
          <span className="kiosk-hero-tag">KIOSK ACTIVATION</span>
          <h1 id="pair-heading" className="kiosk-stage-heading">Pair this kiosk device</h1>
          <p className="kiosk-stage-subheading">
            Enter the one-time pairing code generated by the clinic administrator. Codes expire after 10 minutes.
          </p>
        </div>

        <form className="kiosk-confirm-card kiosk-pair-form" onSubmit={pair}>
          <div className="kiosk-pair-field">
            <label htmlFor="kiosk-pair-code" className="kiosk-pair-label">
              10-Character Pairing Code
            </label>
            <input
              id="kiosk-pair-code"
              name="code"
              className="kiosk-pair-input"
              autoComplete="one-time-code"
              inputMode="text"
              autoCapitalize="characters"
              placeholder="e.g. 7A8B9C1D2E"
              minLength="8"
              maxLength="20"
              required
              value={code}
              onChange={(event) => setCode(event.target.value.toUpperCase())}
            />
          </div>

          {error && (
            <p className="kiosk-inline-banner kiosk-inline-error" role="alert">
              {error}
            </p>
          )}

          <button className="kiosk-btn kiosk-btn-primary kiosk-btn-large kiosk-btn-cta" type="submit" disabled={pending}>
            {pending ? (
              <>
                <span className="kiosk-spinner-btn" aria-hidden="true" />
                <span>Activating device…</span>
              </>
            ) : (
              <>
                <svg viewBox="0 0 24 24" width="22" height="22" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true">
                  <path d="m5 12 5 5L20 7" />
                </svg>
                <span>Activate Kiosk Terminal</span>
              </>
            )}
          </button>

          <p className="kiosk-pair-helper">
            <svg viewBox="0 0 24 24" width="16" height="16" fill="none" stroke="currentColor" strokeWidth="2.2" strokeLinecap="round" strokeLinejoin="round" aria-hidden="true" className="kiosk-pair-helper-icon">
              <rect width="18" height="11" x="3" y="11" rx="2" ry="2" />
              <path d="M7 11V7a5 5 0 0 1 10 0v4" />
            </svg>
            <span>
              Activating this kiosk grants this terminal permission to issue anonymous walk-in tickets.
              Keep this device stationed in the patient lobby.
            </span>
          </p>
        </form>
      </section>

      <footer className="kiosk-footer">
        <div className="kiosk-footer-left">
          <Link to="/kiosk" className="kiosk-footer-link">← Return to ticket kiosk</Link>
        </div>
        <div className="kiosk-footer-right">
          <span>Pairing is restricted to authorized clinic codes.</span>
        </div>
      </footer>
    </main>
  );
}
